/// Options used when turning an `OCSPRequest` into an HTTP POST.
///
/// RFC 6960 transport is intentionally kept separate from response validation.
/// These options only describe the request envelope sent to the responder:
/// timeout, user agent, and caller-supplied headers. Signature verification,
/// freshness checks, responder authorization, and certificate policy remain
/// explicit follow-up steps.
public struct OCSPHTTPOptions: Equatable, Sendable {
    /// Maximum duration allowed for the responder request.
    public let timeout: TimeInterval

    /// User agent written to the request. Set to `nil` to omit the header.
    public let userAgent: String?

    /// Extra headers merged into the request after the default OCSP headers.
    ///
    /// Values here may intentionally override defaults such as `Accept` when a
    /// caller needs to interoperate with a specific responder or proxy.
    public let additionalHeaders: [String: String]

    /// Creates OCSP HTTP transport options.
    public init(
        timeout: TimeInterval = 15,
        userAgent: String? = "rorksign",
        additionalHeaders: [String: String] = [:]
    ) {
        self.timeout = timeout
        self.userAgent = userAgent
        self.additionalHeaders = additionalHeaders
    }
}

/// Raw DER returned by an OCSP responder over HTTP.
///
/// This is a transport result, not a revocation decision. Feed
/// `responseDER` into `parseOCSPResponse(_:)`,
/// `verifyOCSPResponseSignature(_:responderCertificateData:)`, or
/// `validateOCSPResponse(_:matching:responderCertificateData:policy:)` to
/// perform local response checks.
public struct OCSPHTTPFetchReport: Equatable {
    /// OCSP request whose responder URL was contacted.
    public let request: OCSPRequest

    /// DER-encoded OCSPResponse body returned by the responder.
    public let responseDER: Data

    /// HTTP status code returned by the responder.
    public let statusCode: Int

    /// Responder `Content-Type`, when provided.
    public let contentType: String?
}

/// Result of a complete online OCSP status check.
///
/// The report combines transport and local validation. A successful value means
/// the responder returned DER, the BasicOCSPResponse signature verified, one
/// `SingleResponse` matched the request's `CertID`, and the response satisfied
/// the supplied freshness policy. It still does not evaluate Apple trust roots,
/// certificate policy, CRLs, or revocation of a delegated responder certificate.
public struct OCSPStatusCheckReport: Equatable {
    /// HTTP transport result containing the raw responder DER.
    public let fetch: OCSPHTTPFetchReport

    /// Local validation result for the fetched responder DER.
    public let validation: OCSPResponseValidationReport

    /// Request that was sent to the responder.
    public var request: OCSPRequest {
        fetch.request
    }

    /// Matched certificate status from the responder.
    public var certificateStatus: OCSPCertificateStatus {
        validation.matchedResponse.certificateStatus
    }
}

public extension RorkSigner {
    /// Builds the RFC 6960 HTTP POST request for an OCSP query.
    ///
    /// The returned request uses `application/ocsp-request` as the body content
    /// type, advertises `application/ocsp-response`, and carries the DER request
    /// body generated by `makeOCSPRequest(...)`.
    static func makeOCSPURLRequest(
        _ request: OCSPRequest,
        options: OCSPHTTPOptions = OCSPHTTPOptions()
    ) throws -> URLRequest {
        guard options.timeout > 0 else {
            throw RorkSignError.ocsp("OCSP HTTP timeout must be positive.")
        }
        guard let responderURL = request.responderURL else {
            throw RorkSignError.ocsp("OCSP request has no responder URL.")
        }

        var urlRequest = URLRequest(
            url: responderURL,
            cachePolicy: .reloadIgnoringLocalAndRemoteCacheData,
            timeoutInterval: options.timeout
        )
        urlRequest.httpMethod = "POST"
        urlRequest.httpBody = request.derRepresentation
        urlRequest.setValue("application/ocsp-request", forHTTPHeaderField: "Content-Type")
        urlRequest.setValue("application/ocsp-response", forHTTPHeaderField: "Accept")
        urlRequest.setValue(String(request.derRepresentation.count), forHTTPHeaderField: "Content-Length")
        if let userAgent = options.userAgent,
           !userAgent.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            urlRequest.setValue(userAgent, forHTTPHeaderField: "User-Agent")
        }
        for (field, value) in options.additionalHeaders {
            urlRequest.setValue(value, forHTTPHeaderField: field)
        }
        return urlRequest
    }

    /// Sends an OCSP request to its responder URL and returns the DER body.
    ///
    /// This method only performs HTTP transport. It accepts 2xx status codes and
    /// rejects empty bodies; it does not parse or validate the OCSP response.
    /// Call `validateOCSPResponse(_:matching:responderCertificateData:policy:)`
    /// afterward when local verification is needed.
    static func fetchOCSPResponse(
        _ request: OCSPRequest,
        options: OCSPHTTPOptions = OCSPHTTPOptions(),
        session: URLSession = .shared
    ) async throws -> OCSPHTTPFetchReport {
        let urlRequest = try makeOCSPURLRequest(request, options: options)
        let (data, response) = try await session.data(for: urlRequest)
        guard let httpResponse = response as? HTTPURLResponse else {
            throw RorkSignError.ocsp("OCSP responder did not return an HTTP response.")
        }
        guard (200..<300).contains(httpResponse.statusCode) else {
            throw RorkSignError.ocsp(
                "OCSP responder returned HTTP status \(httpResponse.statusCode)."
            )
        }
        guard !data.isEmpty else {
            throw RorkSignError.ocsp("OCSP responder returned an empty body.")
        }
        return OCSPHTTPFetchReport(
            request: request,
            responseDER: data,
            statusCode: httpResponse.statusCode,
            contentType: httpResponse.value(forHTTPHeaderField: "Content-Type")
        )
    }

    /// Performs an online OCSP status check for one certificate and issuer.
    ///
    /// The certificate inputs may be DER certificates or PEM certificate files.
    /// This method builds the RFC 6960 request, optionally overrides the
    /// responder URL for tests or private responders, fetches the DER response,
    /// and validates that response against the request and issuer relationship.
    /// The issuer is used as the default responder-certificate candidate because
    /// many OCSP responses are signed by the issuer and do not embed it.
    static func checkOCSPStatus(
        certificateData: Data,
        issuerCertificateData: Data,
        responderCertificateData: Data? = nil,
        responderURL: URL? = nil,
        policy: OCSPResponseValidationPolicy = OCSPResponseValidationPolicy(),
        httpOptions: OCSPHTTPOptions = OCSPHTTPOptions(),
        session: URLSession = .shared
    ) async throws -> OCSPStatusCheckReport {
        var request = try makeOCSPRequest(
            certificateData: certificateData,
            issuerCertificateData: issuerCertificateData
        )
        if let responderURL {
            request = OCSPRequest(
                derRepresentation: request.derRepresentation,
                responderURL: responderURL,
                issuerNameHash: request.issuerNameHash,
                issuerKeyHash: request.issuerKeyHash,
                serialNumberHex: request.serialNumberHex
            )
        }

        let fetch = try await fetchOCSPResponse(
            request,
            options: httpOptions,
            session: session
        )
        let validation = try validateOCSPResponse(
            fetch.responseDER,
            matching: request,
            responderCertificateData: responderCertificateData ?? issuerCertificateData,
            issuerCertificateData: issuerCertificateData,
            policy: policy
        )
        return OCSPStatusCheckReport(fetch: fetch, validation: validation)
    }

    /// Performs an online OCSP status check from a PEM/DER certificate chain.
    ///
    /// The first certificate is treated as the leaf and the second as its
    /// issuer. This mirrors common PEM chain files used by signing tools. Use
    /// the explicit leaf/issuer overload when the certificates live in separate
    /// files or the chain order is not leaf-first.
    static func checkOCSPStatus(
        certificateChainData: Data,
        responderURL: URL? = nil,
        policy: OCSPResponseValidationPolicy = OCSPResponseValidationPolicy(),
        httpOptions: OCSPHTTPOptions = OCSPHTTPOptions(),
        session: URLSession = .shared
    ) async throws -> OCSPStatusCheckReport {
        let certificates = try SigningIdentity.certificateChainDER(from: certificateChainData)
        guard certificates.count >= 2 else {
            throw RorkSignError.ocsp("OCSP status check requires leaf and issuer certificates.")
        }
        return try await checkOCSPStatus(
            certificateData: certificates[0],
            issuerCertificateData: certificates[1],
            responderCertificateData: certificates[1],
            responderURL: responderURL,
            policy: policy,
            httpOptions: httpOptions,
            session: session
        )
    }

    /// Performs an online OCSP status check for a signing identity.
    ///
    /// PKCS#12 and PEM-chain identities may carry intermediate certificates.
    /// The first additional certificate is used as the issuer for the leaf
    /// certificate. If the identity has no issuer material, callers must use the
    /// explicit leaf/issuer overload instead.
    static func checkOCSPStatus(
        identity: SigningIdentity,
        responderURL: URL? = nil,
        policy: OCSPResponseValidationPolicy = OCSPResponseValidationPolicy(),
        httpOptions: OCSPHTTPOptions = OCSPHTTPOptions(),
        session: URLSession = .shared
    ) async throws -> OCSPStatusCheckReport {
        guard let issuerCertificateDER = identity.additionalCertificatesDER.first else {
            throw RorkSignError.ocsp("OCSP status check requires an issuer certificate.")
        }
        return try await checkOCSPStatus(
            certificateData: identity.certificateDER,
            issuerCertificateData: issuerCertificateDER,
            responderCertificateData: issuerCertificateDER,
            responderURL: responderURL,
            policy: policy,
            httpOptions: httpOptions,
            session: session
        )
    }
}
